export function getThemeBgColor(t: ThemeTokens): string {
  const m = t.bg.match(/#[0-9a-fA-F]{3,8}/);
  if (m) return m[0];
  if (t.bg.includes("white")) return "#ffffff";
  return "#000000";
}
